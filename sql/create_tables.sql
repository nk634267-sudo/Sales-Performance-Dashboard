-- ============================================================================
-- 1. STAGING TABLE (1:1 direct match with cleaned_sales_data.csv)
-- ============================================================================
CREATE TABLE STG_RETAIL_SALES (
    Order_ID          VARCHAR2(30)   NOT NULL,
    Order_Date        VARCHAR2(15)   NOT NULL,
    Product_ID        VARCHAR2(30)   NOT NULL,
    Product_Name      VARCHAR2(150)  NOT NULL,
    Category          VARCHAR2(50)   NOT NULL,
    Sub_Category      VARCHAR2(50)   NOT NULL,
    Quantity          NUMBER(6)      NOT NULL,
    Unit_Price        NUMBER(10, 2)  NOT NULL,
    Discount          NUMBER(5, 2)   DEFAULT 0.00,
    Sales_Amount      NUMBER(12, 2)  NOT NULL,
    Customer_ID       VARCHAR2(30)   NOT NULL,
    Customer_Name     VARCHAR2(100)  NOT NULL,
    Customer_Segment  VARCHAR2(50)   NOT NULL,
    Region            VARCHAR2(50)   NOT NULL,
    Country           VARCHAR2(50)   NOT NULL,
    State             VARCHAR2(50)   NOT NULL,
    City              VARCHAR2(50)   NOT NULL,
    Payment_Method    VARCHAR2(50)   NOT NULL,
    Gross_Amount      NUMBER(12, 2)  NOT NULL,
    Discount_Amount   NUMBER(12, 2)  DEFAULT 0.00,
    Year              NUMBER(4)      NOT NULL,
    Month_Num         NUMBER(2)      NOT NULL,
    Month_Name        VARCHAR2(20)   NOT NULL,
    Year_Month        VARCHAR2(10)   NOT NULL,
    Quarter           VARCHAR2(5)    NOT NULL,
    Day_of_Week       VARCHAR2(15)   NOT NULL
);

COMMENT ON TABLE STG_RETAIL_SALES IS 'Direct staging repository for cleaned retail transaction CSV import.';

-- ============================================================================
-- 2. STAR SCHEMA: DIMENSION TABLES
-- ============================================================================

-- 2.1 Customer Dimension
CREATE TABLE DIM_CUSTOMER (
    Customer_ID       VARCHAR2(30)   PRIMARY KEY,
    Customer_Name     VARCHAR2(100)  NOT NULL,
    Customer_Segment  VARCHAR2(50)   NOT NULL,
    Created_Date      DATE           DEFAULT SYSDATE
);

-- 2.2 Product Dimension
CREATE TABLE DIM_PRODUCT (
    Product_ID        VARCHAR2(30)   PRIMARY KEY,
    Product_Name      VARCHAR2(150)  NOT NULL,
    Category          VARCHAR2(50)   NOT NULL,
    Sub_Category      VARCHAR2(50)   NOT NULL,
    Base_Unit_Price   NUMBER(10, 2)  NOT NULL
);

-- 2.3 Location Dimension
CREATE TABLE DIM_LOCATION (
    Location_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Region            VARCHAR2(50)   NOT NULL,
    Country           VARCHAR2(50)   NOT NULL,
    State             VARCHAR2(50)   NOT NULL,
    City              VARCHAR2(50)   NOT NULL,
    CONSTRAINT UQ_LOCATION UNIQUE (Region, Country, State, City)
);

-- 2.4 Date Dimension
CREATE TABLE DIM_DATE (
    Date_Key          NUMBER(8)      PRIMARY KEY, -- Format YYYYMMDD
    Full_Date         DATE           NOT NULL,
    Year              NUMBER(4)      NOT NULL,
    Quarter           VARCHAR2(5)    NOT NULL,
    Month_Num         NUMBER(2)      NOT NULL,
    Month_Name        VARCHAR2(20)   NOT NULL,
    Year_Month        VARCHAR2(10)   NOT NULL,
    Day_of_Week       VARCHAR2(15)   NOT NULL,
    Is_Weekend        CHAR(1)        CHECK (Is_Weekend IN ('Y', 'N'))
);

-- ============================================================================
-- 3. STAR SCHEMA: FACT TABLE
-- ============================================================================
CREATE TABLE FACT_SALES (
    Sales_Fact_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Order_ID          VARCHAR2(30)   NOT NULL,
    Order_Date        DATE           NOT NULL,
    Date_Key          NUMBER(8)      NOT NULL,
    Customer_ID       VARCHAR2(30)   NOT NULL,
    Product_ID        VARCHAR2(30)   NOT NULL,
    Location_ID       NUMBER         NOT NULL,
    Payment_Method    VARCHAR2(50)   NOT NULL,
    Quantity          NUMBER(6)      NOT NULL CHECK (Quantity > 0),
    Unit_Price        NUMBER(10, 2)  NOT NULL CHECK (Unit_Price > 0),
    Discount          NUMBER(5, 2)   DEFAULT 0.00 CHECK (Discount >= 0 AND Discount <= 1),
    Gross_Amount      NUMBER(12, 2)  NOT NULL CHECK (Gross_Amount >= 0),
    Discount_Amount   NUMBER(12, 2)  DEFAULT 0.00 CHECK (Discount_Amount >= 0),
    Sales_Amount      NUMBER(12, 2)  NOT NULL CHECK (Sales_Amount >= 0),
    -- Foreign Key Constraints
    CONSTRAINT FK_FACT_CUSTOMER FOREIGN KEY (Customer_ID) REFERENCES DIM_CUSTOMER(Customer_ID),
    CONSTRAINT FK_FACT_PRODUCT  FOREIGN KEY (Product_ID)  REFERENCES DIM_PRODUCT(Product_ID),
    CONSTRAINT FK_FACT_LOCATION FOREIGN KEY (Location_ID) REFERENCES DIM_LOCATION(Location_ID),
    CONSTRAINT FK_FACT_DATE     FOREIGN KEY (Date_Key)    REFERENCES DIM_DATE(Date_Key)
);

-- ============================================================================
-- 4. PERFORMANCE INDEXES
-- ============================================================================
CREATE INDEX IDX_FACT_ORDER_DATE ON FACT_SALES(Order_Date);
CREATE INDEX IDX_FACT_CUSTOMER   ON FACT_SALES(Customer_ID);
CREATE INDEX IDX_FACT_PRODUCT    ON FACT_SALES(Product_ID);
CREATE INDEX IDX_FACT_LOCATION   ON FACT_SALES(Location_ID);
CREATE INDEX IDX_FACT_DATE_KEY   ON FACT_SALES(Date_Key);
CREATE INDEX IDX_STG_DATE        ON STG_RETAIL_SALES(Order_Date);

-- ============================================================================
-- 5. ETL STORED PROCEDURE: POPULATE STAR SCHEMA FROM STAGING
-- ============================================================================
CREATE OR REPLACE PROCEDURE POPULATE_STAR_SCHEMA AS
BEGIN
    -- 1. Populate Customer Dimension
    MERGE INTO DIM_CUSTOMER d
    USING (
        SELECT Customer_ID, Customer_Name, Customer_Segment
        FROM (
            SELECT Customer_ID, Customer_Name, Customer_Segment,
                   ROW_NUMBER() OVER (PARTITION BY Customer_ID ORDER BY Order_Date DESC) as rn
            FROM STG_RETAIL_SALES
        ) WHERE rn = 1
    ) s
    ON (d.Customer_ID = s.Customer_ID)
    WHEN NOT MATCHED THEN
        INSERT (Customer_ID, Customer_Name, Customer_Segment)
        VALUES (s.Customer_ID, s.Customer_Name, s.Customer_Segment);

    -- 2. Populate Product Dimension
    MERGE INTO DIM_PRODUCT d
    USING (
        SELECT Product_ID, Product_Name, Category, Sub_Category, Unit_Price
        FROM (
            SELECT Product_ID, Product_Name, Category, Sub_Category, Unit_Price,
                   ROW_NUMBER() OVER (PARTITION BY Product_ID ORDER BY Order_Date DESC) as rn
            FROM STG_RETAIL_SALES
        ) WHERE rn = 1
    ) s
    ON (d.Product_ID = s.Product_ID)
    WHEN NOT MATCHED THEN
        INSERT (Product_ID, Product_Name, Category, Sub_Category, Base_Unit_Price)
        VALUES (s.Product_ID, s.Product_Name, s.Category, s.Sub_Category, s.Unit_Price);

    -- 3. Populate Location Dimension
    MERGE INTO DIM_LOCATION d
    USING (
        SELECT DISTINCT Region, Country, State, City
        FROM STG_RETAIL_SALES
    ) s
    ON (d.Region = s.Region AND d.Country = s.Country AND d.State = s.State AND d.City = s.City)
    WHEN NOT MATCHED THEN
        INSERT (Region, Country, State, City)
        VALUES (s.Region, s.Country, s.State, s.City);

    -- 4. Populate Date Dimension
    MERGE INTO DIM_DATE d
    USING (
        SELECT DISTINCT
            TO_NUMBER(TO_CHAR(TO_DATE(Order_Date, 'YYYY-MM-DD'), 'YYYYMMDD')) AS Date_Key,
            TO_DATE(Order_Date, 'YYYY-MM-DD') AS Full_Date,
            Year,
            Quarter,
            Month_Num,
            Month_Name,
            Year_Month,
            Day_of_Week,
            CASE WHEN Day_of_Week IN ('Saturday', 'Sunday') THEN 'Y' ELSE 'N' END AS Is_Weekend
        FROM STG_RETAIL_SALES
    ) s
    ON (d.Date_Key = s.Date_Key)
    WHEN NOT MATCHED THEN
        INSERT (Date_Key, Full_Date, Year, Quarter, Month_Num, Month_Name, Year_Month, Day_of_Week, Is_Weekend)
        VALUES (s.Date_Key, s.Full_Date, s.Year, s.Quarter, s.Month_Num, s.Month_Name, s.Year_Month, s.Day_of_Week, s.Is_Weekend);

    -- 5. Populate Fact Sales Table
    EXECUTE IMMEDIATE 'TRUNCATE TABLE FACT_SALES';
    
    INSERT INTO FACT_SALES (
        Order_ID,
        Order_Date,
        Date_Key,
        Customer_ID,
        Product_ID,
        Location_ID,
        Payment_Method,
        Quantity,
        Unit_Price,
        Discount,
        Gross_Amount,
        Discount_Amount,
        Sales_Amount
    )
    SELECT
        s.Order_ID,
        TO_DATE(s.Order_Date, 'YYYY-MM-DD') AS Order_Date,
        TO_NUMBER(TO_CHAR(TO_DATE(s.Order_Date, 'YYYY-MM-DD'), 'YYYYMMDD')) AS Date_Key,
        s.Customer_ID,
        s.Product_ID,
        loc.Location_ID,
        s.Payment_Method,
        s.Quantity,
        s.Unit_Price,
        s.Discount,
        s.Gross_Amount,
        s.Discount_Amount,
        s.Sales_Amount
    FROM STG_RETAIL_SALES s
    JOIN DIM_LOCATION loc
      ON s.Region = loc.Region
     AND s.Country = loc.Country
     AND s.State = loc.State
     AND s.City = loc.City;

    COMMIT;
END;
/

